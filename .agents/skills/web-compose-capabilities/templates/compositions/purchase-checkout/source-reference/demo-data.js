    const prefix = org === "workspace" ? "W" : "S"
    records.set(org, {
      balance: org === "workspace" ? 50000 : 26000,
      orders: ["pending", "paid", "closed", "expired", "processing", "unknown"].map(
        (status, i) => ({
          id: `DEMO-${prefix}-${String(i + 1).padStart(3, "0")}`,
          product: products[i % products.length],
          amount: products[i % products.length].amount,
          status,
          org,
          created: `2000-01-01 ${String(10 + i).padStart(2, "0")}:00`,
          refreshFailed: false
        })
      ),
      ledger: [
        { id: "DEMO-" + prefix + "-002", amount: -9900, type: "expense", time: "2000-01-01 11:00" },
        { id: "—", amount: 59900, type: "income", time: "2000-01-01 09:00" }
      ],
      requests: new Map()
    })
